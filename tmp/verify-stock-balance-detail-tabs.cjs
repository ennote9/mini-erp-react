const fs = require("fs/promises");
const path = require("path");
const { chromium } = require("playwright");

const APP_ROOT = "http://127.0.0.1:1420";
const LIST_URL = `${APP_ROOT}/stock-balances`;
const INJECT_DEFICIT = process.env.INJECT_DEFICIT === "1";
const OUT_JSON = path.join(
  process.cwd(),
  "tmp",
  INJECT_DEFICIT
    ? "stock-balance-detail-tabs-deficit.json"
    : "stock-balance-detail-tabs-baseline.json",
);

function toNumber(text) {
  const normalized = (text || "")
    .replace(/\s/g, "")
    .replace(/[^\d,.-]/g, "")
    .replace(",", ".");
  const value = Number(normalized);
  return Number.isFinite(value) ? value : NaN;
}

async function ensureDeficitScenario(page) {
  return page.evaluate(async () => {
    const [{ salesOrderService }, { salesOrderRepository }, { itemRepository }, { stockBalanceRepository }] =
      await Promise.all([
        import("/src/modules/sales-orders/service.ts"),
        import("/src/modules/sales-orders/repository.ts"),
        import("/src/modules/items/repository.ts"),
        import("/src/modules/stock-balances/repository.ts"),
      ]);

    const existingConfirmed = salesOrderRepository
      .list()
      .find((so) => so.customerId === "1" && so.warehouseId === "1" && so.status === "confirmed");

    if (!existingConfirmed) {
      const item = itemRepository.getById("1");
      const unitPrice =
        typeof item?.salePrice === "number" && Number.isFinite(item.salePrice) && item.salePrice > 0
          ? item.salePrice
          : 100;
      const createResult = salesOrderService.saveDraft({
        date: new Date().toISOString().slice(0, 10),
        customerId: "1",
        warehouseId: "1",
        comment: "autogenerated deficit verification",
        lines: [{ itemId: "1", qty: 5, unitPrice }],
      });
      if (createResult.success) {
        salesOrderService.confirm(createResult.id);
      }
    }

    stockBalanceRepository.upsert({
      itemId: "1",
      warehouseId: "1",
      style: "GOOD",
      qtyOnHand: 0,
    });
    return true;
  });
}

async function extractFirstRow(page) {
  const rows = await page.evaluate(() =>
    Array.from(document.querySelectorAll(".ag-center-cols-container .ag-row")).map((row, index) => {
      const read = (colId) => (row.querySelector(`[col-id="${colId}"]`)?.textContent || "").trim();
      return {
        index,
        itemCode: read("itemCode"),
        netShortageText: read("netShortageQty"),
        coverage: read("coverageStatus"),
      };
    }),
  );
  if (rows.length === 0) return null;
  return { ...rows[0], netShortage: toNumber(rows[0].netShortageText) };
}

async function openDetailFromFirstRow(page) {
  await page.locator('.ag-center-cols-container .ag-row[row-index="0"] [col-id="itemCode"]').first().click();
  await page.waitForURL(/\/stock-balances\/[^/?#]+(?:\?.*)?$/);
}

async function collectSnapshot(page) {
  return page.evaluate(() => {
    const text = (sel) => (document.querySelector(sel)?.textContent || "").trim();
    const utilityButtons = Array.from(document.querySelectorAll(".doc-page__breadcrumb button")).map((n) =>
      (n.textContent || "").trim(),
    );
    const tabTriggers = Array.from(document.querySelectorAll('[role="tab"]')).map((n) =>
      (n.textContent || "").trim(),
    );
    const activeTab = (
      document.querySelector('[role="tab"][data-state="active"]')?.textContent || ""
    ).trim();
    const rect = (sel) => {
      const el = document.querySelector(sel);
      if (!el) return null;
      const r = el.getBoundingClientRect();
      return { x: r.x, width: r.width };
    };
    const viewportWidth = window.innerWidth;
    return {
      header: text("h2"),
      utilityButtons,
      tabTriggers,
      activeTab,
      hasRightRail: !!document.querySelector("aside"),
      hasMovementsSection:
        !!Array.from(document.querySelectorAll("section h3")).find((n) =>
          (n.textContent || "").toLowerCase().includes("movements") ||
          (n.textContent || "").toLowerCase().includes("движени"),
        ),
      bounds: {
        viewportWidth,
        wrapper: rect(".doc-page > .max-w-\\[1120px\\]"),
        utilityRow: rect(".doc-page__breadcrumb"),
        headerCard: rect(".doc-page .card"),
        tabs: rect('[role="tablist"]'),
        tabContent: rect('[data-state=\"active\"][role=\"tabpanel\"]'),
      },
    };
  });
}

async function main() {
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1720, height: 1180 }, colorScheme: "dark" });
  const page = await context.newPage();
  const consoleErrors = [];
  page.on("console", (msg) => {
    if (msg.type() === "error") consoleErrors.push(msg.text());
  });
  page.on("pageerror", (error) => consoleErrors.push(error.message));

  try {
    await page.goto(LIST_URL, { waitUntil: "networkidle" });
    await page.waitForSelector(".ag-root");
    if (INJECT_DEFICIT) {
      await ensureDeficitScenario(page);
      await page.reload({ waitUntil: "networkidle" });
      await page.waitForSelector(".ag-root");
    }

    const firstRow = await extractFirstRow(page);
    await openDetailFromFirstRow(page);
    await page.waitForTimeout(200);

    const snapshot = await collectSnapshot(page);
    await page.screenshot({
      path: path.join(process.cwd(), "tmp", INJECT_DEFICIT ? "stock-balance-tabs-deficit.png" : "stock-balance-tabs-baseline.png"),
      fullPage: true,
    });

    await page.getByRole("tab", { name: /Outbound Demand|Исходящий спрос/ }).click();
    const outboundVisible = await page.getByText(/Sales order|Заказ клиента/i).first().isVisible().catch(() => false);

    await page.getByRole("tab", { name: /Inbound Supply|Входящие поставки/ }).click();
    const inboundVisible = await page.getByText(/Purchase order|Заказ поставщику/i).first().isVisible().catch(() => false);

    await page.getByRole("tab", { name: /Active Reservations|Активные резервы/ }).click();
    const reservationsVisible = await page
      .locator("text=No active reservations")
      .first()
      .isVisible()
      .catch(() => false);

    await page.getByRole("tab", { name: /Operational Summary|Операционная сводка/ }).click();

    const actionButton = page.getByRole("button", { name: /Open stock movements|Открыть движения/ }).first();
    let actionNavigation = null;
    if (await actionButton.isVisible()) {
      await actionButton.click();
      await page.waitForURL(/\/stock-movements(?:\?.*)?$/);
      actionNavigation = page.url();
    }

    const result = {
      injectedDeficit: INJECT_DEFICIT,
      firstRow,
      snapshot,
      tabsSwitchCheck: {
        outboundVisible,
        inboundVisible,
        reservationsVisible,
      },
      actionNavigation,
      consoleErrors,
    };
    await fs.writeFile(OUT_JSON, JSON.stringify(result, null, 2));
    console.log(OUT_JSON);
    console.log(JSON.stringify(result, null, 2));
  } finally {
    await context.close();
    await browser.close();
  }
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
