const fs = require("fs/promises");
const path = require("path");
const { chromium } = require("playwright");

const APP_ROOT = "http://127.0.0.1:1420";
const LIST_URL = `${APP_ROOT}/stock-balances`;
const SKIP_INJECTION = process.env.SKIP_INJECTION === "1";
const OUT_JSON = path.join(
  process.cwd(),
  "tmp",
  SKIP_INJECTION
    ? "stock-balance-detail-explainability-baseline.json"
    : "stock-balance-detail-explainability-verification.json",
);

function toNumber(text) {
  const normalized = (text || "")
    .replace(/\s/g, "")
    .replace(/[^\d,.-]/g, "")
    .replace(",", ".");
  const value = Number(normalized);
  return Number.isFinite(value) ? value : NaN;
}

async function extractListRows(page) {
  return page.evaluate(() => {
    const rows = Array.from(document.querySelectorAll(".ag-center-cols-container .ag-row"));
    return rows.map((row, idx) => {
      const read = (colId) => (row.querySelector(`[col-id="${colId}"]`)?.textContent || "").trim();
      return {
        index: idx,
        id: row.getAttribute("row-id") || "",
        itemCode: read("itemCode"),
        coverage: read("coverageStatus"),
        netShortageText: read("netShortageQty"),
      };
    });
  });
}

async function collectDetailSnapshot(page) {
  return page.evaluate(() => {
    const text = (sel) => (document.querySelector(sel)?.textContent || "").trim();
    const actionButtons = Array.from(document.querySelectorAll("aside button")).map((n) =>
      (n.textContent || "").trim(),
    );
    const sectionTitles = Array.from(document.querySelectorAll("section h3")).map((n) =>
      (n.textContent || "").trim(),
    );
    const explainCandidate = Array.from(document.querySelectorAll(".doc-page p"))
      .map((n) => (n.textContent || "").trim())
      .find((value) => value.length > 30);
    return {
      url: window.location.href,
      header: text("h2"),
      explainLine: explainCandidate || "",
      hasKpiStrip: !!Array.from(document.querySelectorAll(".card .text-sm")).find((n) =>
        (n.textContent || "").toLowerCase().includes("операц") ||
        (n.textContent || "").toLowerCase().includes("operational"),
      ),
      hasExplainability: sectionTitles.some((x) => x.length > 0),
      sectionTitles,
      actionButtons,
      hasMovementsTable:
        !!document.querySelector('section[aria-labelledby="sb-src-movements"] table') ||
        !!document.querySelector('section[aria-labelledby="sb-src-movements"] p'),
    };
  });
}

async function ensureDeficitScenario(page) {
  return page.evaluate(async () => {
    const [{ salesOrderService }, { salesOrderRepository }, { itemRepository }, { stockBalanceRepository }] =
      await Promise.all([
        import("/src/modules/sales-orders/service.ts"),
        import("/src/modules/sales-orders/repository.ts"),
        import("/src/modules/items/repository.ts"),
        import("/src/modules/stock-balances/repository.ts"),
      ]);

    const existingConfirmed = salesOrderRepository
      .list()
      .find((so) => so.customerId === "1" && so.warehouseId === "1" && so.status === "confirmed");

    if (!existingConfirmed) {
      const item = itemRepository.getById("1");
      const unitPrice =
        typeof item?.salePrice === "number" && Number.isFinite(item.salePrice) && item.salePrice > 0
          ? item.salePrice
          : 100;
      const createResult = salesOrderService.saveDraft({
        date: new Date().toISOString().slice(0, 10),
        customerId: "1",
        warehouseId: "1",
        comment: "autogenerated deficit verification",
        lines: [{ itemId: "1", qty: 5, unitPrice }],
      });
      if (createResult.success) {
        salesOrderService.confirm(createResult.id);
      }
    }

    const balance = stockBalanceRepository.getByItemAndWarehouse("1", "1");
    if (!balance || balance.qtyOnHand !== 0) {
      stockBalanceRepository.upsert({
        itemId: "1",
        warehouseId: "1",
        style: "GOOD",
        qtyOnHand: 0,
      });
    }
    stockBalanceRepository.upsert({
      itemId: "1",
      warehouseId: "1",
      style: "MARKDOWN",
      qtyOnHand: 3,
    });

    return {
      confirmedSalesOrders: salesOrderRepository
        .list()
        .filter((so) => so.customerId === "1" && so.warehouseId === "1" && so.status === "confirmed").length,
    };
  });
}

async function openRowAndCapture(page, rowIndex, screenshotName) {
  const row = page.locator(`.ag-center-cols-container .ag-row[row-index="${rowIndex}"] [col-id="itemCode"]`).first();
  await row.click();
  await page.waitForURL(/\/stock-balances\/[^/?#]+(?:\?.*)?$/);
  await page.waitForTimeout(200);
  const detail = await collectDetailSnapshot(page);
  await page.screenshot({ path: path.join(process.cwd(), "tmp", screenshotName), fullPage: true });
  return detail;
}

async function main() {
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1720, height: 1180 }, colorScheme: "dark" });
  const page = await context.newPage();

  try {
    const consoleErrors = [];
    page.on("console", (msg) => {
      if (msg.type() === "error") consoleErrors.push(msg.text());
    });
    page.on("pageerror", (error) => consoleErrors.push(error.message));

    await page.goto(LIST_URL, { waitUntil: "networkidle" });
    await page.waitForSelector(".ag-root");
    const injected = SKIP_INJECTION ? null : await ensureDeficitScenario(page);
    if (!SKIP_INJECTION) {
      await page.reload({ waitUntil: "networkidle" });
      await page.waitForSelector(".ag-root");
    }

    const rows = await extractListRows(page);
    const enriched = rows.map((r) => ({ ...r, netShortage: toNumber(r.netShortageText) }));
    const deficitRow = enriched.find((r) => Number.isFinite(r.netShortage) && r.netShortage > 0);
    const nonDeficitRow = enriched.find((r) => Number.isFinite(r.netShortage) && r.netShortage <= 0);

    const summary = {
      listRowCount: rows.length,
      deficitRow: deficitRow || null,
      nonDeficitRow: nonDeficitRow || null,
      deficitDetail: null,
      nonDeficitDetail: null,
      injected,
      actionNavigationCheck: null,
      consoleErrors,
    };

    await page.screenshot({
      path: path.join(process.cwd(), "tmp", "stock-balance-detail-list-before.png"),
      fullPage: true,
    });

    if (deficitRow) {
      summary.deficitDetail = await openRowAndCapture(
        page,
        deficitRow.index,
        "stock-balance-detail-deficit.png",
      );
      const movementButton = page.getByRole("button", { name: /Open stock movements|Открыть движения/ }).first();
      if (await movementButton.isVisible()) {
        await movementButton.click();
        await page.waitForURL(/\/stock-movements(?:\?.*)?$/);
        summary.actionNavigationCheck = { toStockMovements: page.url() };
        await page.goBack({ waitUntil: "networkidle" });
      }
      await page.goBack({ waitUntil: "networkidle" });
      await page.waitForSelector(".ag-root");
    }

    if (nonDeficitRow) {
      summary.nonDeficitDetail = await openRowAndCapture(
        page,
        nonDeficitRow.index,
        "stock-balance-detail-non-deficit.png",
      );
      await page.goBack({ waitUntil: "networkidle" });
      await page.waitForSelector(".ag-root");
    }

    await fs.writeFile(OUT_JSON, JSON.stringify(summary, null, 2));
    console.log(OUT_JSON);
    console.log(JSON.stringify(summary, null, 2));
  } finally {
    await context.close();
    await browser.close();
  }
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
